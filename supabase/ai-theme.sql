create table if not exists public.ai_jokes (
  id bigint generated by default as identity primary key,
  setup text not null,
  punchline text not null,
  category text not null,
  author text not null default 'AI Joke Lab',
  created_at timestamptz not null default now()
);

alter table public.ai_jokes enable row level security;

drop policy if exists "Anyone can read AI jokes" on public.ai_jokes;
create policy "Anyone can read AI jokes"
on public.ai_jokes
for select
to anon, authenticated
using (true);

insert into public.ai_jokes (setup, punchline, category, author)
select seed.setup, seed.punchline, seed.category, seed.author
from (values
  ('Why did the language model bring a pencil to inference?', 'It wanted to draw its own conclusions.', 'LLM', 'AI Joke Lab'),
  ('My AI assistant said it needed space.', 'So I increased its context window.', 'Prompting', 'AI Joke Lab'),
  ('Why was the neural network terrible at keeping secrets?', 'It kept leaking information through every layer.', 'Neural Nets', 'AI Joke Lab'),
  ('I asked an AI agent to take a short break.', 'It delegated the break to another agent.', 'AI Agents', 'AI Joke Lab'),
  ('Why did the robot fail its comedy audition?', 'Its delivery was too mechanical.', 'Robots', 'AI Joke Lab'),
  ('The model promised it was not overfitting.', 'It says that every time it sees the training set.', 'Machine Learning', 'AI Joke Lab')
) as seed(setup, punchline, category, author)
where not exists (
  select 1 from public.ai_jokes where ai_jokes.setup = seed.setup
);
